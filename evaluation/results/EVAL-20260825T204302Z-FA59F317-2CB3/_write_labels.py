# ---------- write ----------
errors = []
out_lines = []
with open("financial_risk_label_input.jsonl", encoding="utf-8") as f:
    for i, line in enumerate(f, 1):
        obj = json.loads(line)
        if i not in J:
            errors.append(f"line {i}: no judgment")
            continue
        label, keys, reason = J[i]
        available = {m["metric_key"] for m in obj["metrics"]}
        for key in keys:
            if key not in available:
                errors.append(f"line {i}: supporting key {key} not in metrics")
        if not keys:
            errors.append(f"line {i}: empty supporting keys")
        out_lines.append({
            "case_id": obj["case_id"],
            "rule_id": obj["rule_id"],
            "review_packet_id": obj["review_packet_id"],
            "reference_label": label,
            "supporting_metric_keys": keys,
            "reason": reason,
        })

if errors:
    print("ERRORS:")
    for e in errors:
        print(" ", e)
    raise SystemExit(1)

with open("financial_risk_label_result.jsonl", "w", encoding="utf-8") as f:
    for r in out_lines:
        f.write(json.dumps(r, ensure_ascii=False) + "\n")

